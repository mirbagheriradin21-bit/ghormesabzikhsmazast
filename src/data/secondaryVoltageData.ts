// Analyze voltage stability
export function analyzeVoltageRow(row: SecondaryVoltageRow): { analysis: string; status: "normal" | "warning" | "critical" | "optimal" } {
  const range = row.V_car_max - row.V_car_min;
  
  // Critical: Extreme voltage spike
  if (row.V_car_max > 60) {
    return {
      analysis: `🚨 CRITICAL SPIKE: ${row.V_car_max.toFixed(2)}V detected. Possible sensor anomaly or regenerative surge.`,
      status: "critical"
    };
  }
  
  // Critical: Very low voltage
  if (row.V_car_min < 36) {
    return {
      analysis: `⚠️ LOW VOLTAGE: Min ${row.V_car_min.toFixed(2)}V. Battery under extreme load or depletion.`,
      status: "critical"
    };
  }
  
  // Warning: High variation
  if (range > 5) {
    return {
      analysis: `📊 HIGH VARIATION: ${range.toFixed(2)}V range. Unstable power delivery detected.`,
      status: "warning"
    };
  }
  
  // Warning: Moderate drop
  if (row.V_car_avg < 42) {
    return {
      analysis: `🔋 VOLTAGE DROP: Avg ${row.V_car_avg.toFixed(2)}V. Consider reducing power draw.`,
      status: "warning"
    };
  }
  
  // Optimal: Perfect stability
  if (range < 0.1) {
    return {
      analysis: `✅ PERFECT STABILITY: Zero variation at ${row.V_car_last.toFixed(2)}V.`,
      status: "optimal"
    };
  }
  
  // Optimal: Good stability
  if (range < 0.3 && row.V_car_avg > 45) {
    return {
      analysis: `✅ OPTIMAL: Stable at ${row.V_car_avg.toFixed(2)}V with minimal variation.`,
      status: "optimal"
    };
  }
  
  // Normal
  return {
    analysis: `📈 STABLE: ${row.V_car_last.toFixed(2)}V (${row.V_car_min.toFixed(2)}-${row.V_car_max.toFixed(2)}V range).`,
    status: "normal"
  };
}

// Get voltage summary
export function getVoltageSummary() {
  const data = secondaryVoltageData;
  return {
    avgVoltage: data.reduce((a, d) => a + d.V_car_avg, 0) / data.length,
    minVoltage: Math.min(...data.map(d => d.V_car_min)),
    maxVoltage: Math.max(...data.map(d => d.V_car_max)),
    avgRange: data.reduce((a, d) => a + (d.V_car_max - d.V_car_min), 0) / data.length,
    spikeCount: data.filter(d => d.V_car_max > 50).length,
    dropCount: data.filter(d => d.V_car_min < 40).length,
    totalReadings: data.length,
  };
}
